function stubGhApi(response: { stdout?: string; stderr?: string; success?: boolean } = { stdout: '{}' }) {
  ctx.commands.on(['gh', 'api'], response)
}

function lastApiCall() {
  const call = ctx.commands.commandsMatching(['gh', 'api']).at(-1)
  if (!call) throw new Error('gh api was not called')
  return call
}

function sentPayload() {
  const parsed: unknown = JSON.parse(lastApiCall().options.input ?? 'null')
  if (!isRecord(parsed)) throw new Error('gh api payload is not an object')
  return parsed
}

function sentEndpoint() {
  const { command } = lastApiCall()
  return command[command.indexOf('--input') - 1]
}

function sentMethod() {
  const { command } = lastApiCall()
  return command[command.indexOf('--method') + 1]
}

function sentComments() {
  const comments = sentPayload().comments
  if (!Array.isArray(comments)) throw new Error('payload has no comments')
  return comments
}

describe('validateEvent', () => {
  test.each(['APPROVE', 'REQUEST_CHANGES', 'COMMENT'])('accepts %s', (event) => {
    expect(() => validateEvent(event)).not.toThrow()
  })

  test('raises for an invalid event, listing the valid ones', () => {
    const invalidEvent = 'INVALID'
    const validEvents = ['APPROVE', 'REQUEST_CHANGES', 'COMMENT']

    expect(() => validateEvent(invalidEvent)).toThrow(GithubReviewSubmitterError)
    expect(() => validateEvent(invalidEvent)).toThrow(`Invalid review event: ${invalidEvent}. Must be one of: ${validEvents.join(', ')}`)
  })

  test.each(['approve', 'Approve'])('is case sensitive (%s)', (event) => {
    expect(() => validateEvent(event)).toThrow(GithubReviewSubmitterError)
  })
})

describe('buildReviewBody', () => {
  test('summarizes counts per severity', () => {
    const comments = [criticalComment, minorComment]

    const body = buildReviewBody(comments)

    expect(body).toContain('## Code Review Summary')
    expect(body).toContain(`Found **${comments.length}** issues`)
    expect(body).toContain(`- ${severityEmoji(criticalComment.severity)} **Critical**: 1`)
    expect(body).toContain(`- ${severityEmoji(minorComment.severity)} **Minor**: 1`)
  })

  test('includes the footer', () => {
    expect(buildReviewBody([criticalComment])).toContain('_Review generated by Forge_')
  })

  test('uses the custom summary when provided', () => {
    const customSummary = 'Custom summary'

    expect(buildReviewBody([criticalComment], customSummary)).toBe(customSummary)
  })
})

describe('determineEvent', () => {
  test('requests changes for critical issues', () => {
    expect(determineEvent([criticalComment])).toBe('REQUEST_CHANGES')
  })

  test('requests changes for major issues', () => {
    const majorComment = { ...criticalComment, severity: 'major' }

    expect(determineEvent([majorComment])).toBe('REQUEST_CHANGES')
  })

  test('comments for minor issues', () => {
    expect(determineEvent([minorComment])).toBe('COMMENT')
  })

  test('comments for suggestions', () => {
    expect(determineEvent([fileLevelComment])).toBe('COMMENT')
  })

  test('comments when nothing is critical or major', () => {
    expect(determineEvent([minorComment, fileLevelComment])).toBe('COMMENT')
  })

  test('requests changes with mixed severities', () => {
    expect(determineEvent([criticalComment, minorComment, fileLevelComment])).toBe('REQUEST_CHANGES')
  })
})

describe('buildReviewComments', () => {
  test('includes every comment with a file path, in order', () => {
    const comments = [criticalComment, minorComment, fileLevelComment]

    const payloads = buildReviewComments(comments)

    expect(payloads.map((payload) => payload.path)).toEqual(comments.map((comment) => comment.filePath))
  })

  test('includes line and side when the comment has a line number', () => {
    const [payload] = buildReviewComments([criticalComment])

    expect(payload?.line).toBe(criticalComment.lineNumber ?? undefined)
    expect(payload?.side).toBe('RIGHT')
  })

  test.each(['N/A', ' n/a '])('skips comments whose file path is %p', (filePath) => {
    const unmappedComment = insertReviewComment(ctx.db, { reviewTaskId: task.id, body: 'Cannot map file path', filePath, severity: 'major' })

    expect(buildReviewComments([unmappedComment])).toEqual([])
  })
})

describe('buildCommentPayload', () => {
  test('includes path, line, side and a badged body', () => {
    const payload = buildCommentPayload(criticalComment)

    expect(payload).toEqual({
      path: criticalComment.filePath,
      body: `${severityBadge(criticalComment.severity)}\n\n${criticalComment.body}`,
      line: criticalComment.lineNumber ?? undefined,
      side: 'RIGHT',
    })
  })

  test('omits line and side without a line number', () => {
    const payload = buildCommentPayload(fileLevelComment)

    expect(payload).not.toHaveProperty('line')
    expect(payload).not.toHaveProperty('side')
  })
})

describe('formatUserFriendlyError', () => {
  const prefix = 'GitHub API error: '

  test('collapses and trims whitespace', () => {
    const words = ['too', 'many', 'spaces']

    expect(formatUserFriendlyError(`  ${words.join('   ')}  `)).toBe(`${prefix}${words.join(' ')}`)
  })

  test('truncates long messages to 200 characters', () => {
    const truncatedLength = 200
    const longMessage = 'x'.repeat(300)

    const message = formatUserFriendlyError(longMessage)

    expect(message).toHaveLength(prefix.length + truncatedLength)
    expect(message.endsWith('...')).toBe(true)
  })

  test('prefixes the message', () => {
    const original = 'something went wrong'

    expect(formatUserFriendlyError(original)).toBe(`${prefix}${original}`)
  })
})

