describe('extractRateLimitReset', () => {
  test('parses an ISO8601 timestamp as local time, ignoring the zone suffix like Ruby', () => {
    const [year, month, day, hour] = [2024, 1, 1, 12]
    const stderr = `rate limit resets at ${year}-0${month}-0${day}T${hour}:00:00Z`

    expect(extractRateLimitReset(stderr)).toEqual(new Date(year, month - 1, day, hour, 0, 0))
  })

  test('parses a seconds countdown relative to now', () => {
    const now = new Date()
    const seconds = 300

    expect(extractRateLimitReset(`rate limit resets in ${seconds} seconds remaining`, now)).toEqual(new Date(now.getTime() + seconds * 1000))
  })

  test('returns null for unknown formats', () => {
    expect(extractRateLimitReset('unknown error format')).toBeNull()
  })
})

